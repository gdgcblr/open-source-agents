"""Render reports: a Markdown PR review and an HTML triage dashboard."""

from __future__ import annotations

import html
import json
from datetime import datetime, timezone

from .models import Report, Severity, Verdict

BADGE = {
    Verdict.READY: "✅ **Ready for maintainer review**",
    Verdict.CHANGES_REQUESTED: "🛠️ **Changes requested**",
    Verdict.BLOCKED: "⛔ **Blocked**",
}
ICON = {Severity.BLOCKER: "⛔", Severity.MAJOR: "🔴", Severity.MINOR: "🟡", Severity.INFO: "ℹ️"}
MARKER = "<!-- contribution-gatekeeper -->"


def _bar(n: int) -> str:
    return "█" * (n // 10) + "░" * (10 - n // 10)


def markdown(rep: Report, intro: str | None = None, strengths: list[str] | None = None) -> str:
    sub = rep.submission
    lines = [MARKER, f"## Contribution Gatekeeper review: `{sub.project_dir or 'unknown project'}`", ""]
    lines += [f"{BADGE[rep.verdict]} · score **{rep.score()}/100**", ""]
    if intro:
        lines += [intro.strip(), ""]
    elif strengths:
        lines += ["**What's good:** " + "; ".join(strengths[:3]), ""]

    lines += ["| Criterion | Score | |", "| :--- | ---: | :--- |"]
    for crit, s in rep.scores().items():
        lines.append(f"| {crit} | {s} | `{_bar(s)}` |")
    lines.append("")

    order = sorted(rep.findings, key=lambda f: (-f.severity.rank, f.criterion.value))
    actionable = [f for f in order if f.severity != Severity.INFO]
    if actionable:
        lines += [f"### What to fix ({len(actionable)})", ""]
        for f in actionable:
            loc = f" · `{f.file}{':' + str(f.line) if f.line else ''}`" if f.file else ""
            tag = " · _AI review_" if f.source == "llm" else ""
            lines.append(f"- {ICON[f.severity]} **{f.severity.value}** · {f.criterion.value}{loc}{tag}  ")
            lines.append(f"  {f.message}")
            if f.fix:
                lines.append(f"  - **Fix:** {f.fix}")
            if f.rule:
                lines.append(f"  - **Rule:** _{f.rule}_")
        lines.append("")
    else:
        lines += ["### No issues found", "", "Every automated check passed. A maintainer will take it from here.", ""]

    notes = [f for f in order if f.severity == Severity.INFO]
    if notes:
        lines += ["<details><summary>Notes for maintainers</summary>", ""]
        lines += [f"- {f.message}" for f in notes]
        lines += ["", "</details>", ""]

    mode = "deterministic checks + Gemini review (ADK)" if rep.llm_used else "deterministic checks only"
    lines += ["---",
              f"<sub>🤖 Generated by contribution-gatekeeper ({mode}). Rules are read from the base branch's "
              "CONTRIBUTING.md; AI findings must quote the submission and can never override or clear a "
              "deterministic check. A human maintainer makes the final decision.</sub>"]
    return "\n".join(lines)


def to_json(rep: Report) -> dict:
    s = rep.submission
    return {
        "url": s.url, "number": s.number, "title": s.title, "author": s.author,
        "project": s.project_dir, "verdict": rep.verdict.value, "score": rep.score(),
        "scores": rep.scores(), "llm_used": rep.llm_used, "sandbox": rep.sandbox,
        "findings": [f.to_dict() for f in rep.findings],
    }


def dashboard(reports: list[dict], repo: str) -> str:
    """Single-file HTML triage board, sorted so maintainers review ready PRs first."""
    rank = {"ready": 0, "changes_requested": 1, "blocked": 2, "error": 3}
    reports = sorted(reports, key=lambda r: (rank.get(r["verdict"], 9), -r.get("score", 0)))
    counts = {k: sum(r["verdict"] == k for r in reports) for k in rank}
    label = {"ready": "Ready", "changes_requested": "Changes requested", "blocked": "Blocked", "error": "Error"}
    rows = []
    for r in reports:
        top = [f for f in r.get("findings", []) if f["severity"] in ("blocker", "major")][:3]
        issues = "".join(f"<li class='{f['severity']}'>{html.escape(f['message'][:160])}</li>" for f in top)
        rows.append(
            f"<tr data-v='{r['verdict']}'><td><a href='{html.escape(r.get('url') or '#')}'>#{r.get('number')}</a></td>"
            f"<td><b>{html.escape(r.get('project') or '-')}</b><br><small>{html.escape(r.get('title') or '')}"
            f" · @{html.escape(r.get('author') or '?')}</small></td>"
            f"<td><span class='pill {r['verdict']}'>{label.get(r['verdict'], r['verdict'])}</span></td>"
            f"<td class='num'>{r.get('score', '-')}</td><td><ul>{issues or '<li>No blocking issues</li>'}</ul></td></tr>"
        )
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>PR Triage Board</title>
<style>
:root{{--bg:#fafaf9;--fg:#1c1917;--mut:#78716c;--card:#fff;--line:#e7e5e4;--ok:#15803d;--warn:#b45309;--bad:#b91c1c}}
@media (prefers-color-scheme:dark){{:root{{--bg:#1c1917;--fg:#f5f5f4;--mut:#a8a29e;--card:#292524;--line:#44403c;--ok:#4ade80;--warn:#fbbf24;--bad:#f87171}}}}
body{{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif}}
main{{max-width:1100px;margin:0 auto;padding:24px 16px}} h1{{margin:0 0 4px;font-size:24px}}
.sub{{color:var(--mut);margin-bottom:20px}} .stats{{display:flex;gap:12px;flex-wrap:wrap;margin-bottom:20px}}
.stat{{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:12px 16px;min-width:120px;cursor:pointer}}
.stat b{{display:block;font-size:26px}} table{{width:100%;border-collapse:collapse;background:var(--card);border:1px solid var(--line);border-radius:10px;overflow:hidden}}
td,th{{padding:10px 12px;border-bottom:1px solid var(--line);text-align:left;vertical-align:top}} th{{font-size:12px;text-transform:uppercase;color:var(--mut)}}
.num{{font-variant-numeric:tabular-nums;font-weight:600}} ul{{margin:0;padding-left:18px}} small{{color:var(--mut)}} a{{color:inherit}}
.pill{{padding:2px 8px;border-radius:99px;font-size:12px;font-weight:600;white-space:nowrap;border:1px solid}}
.ready{{color:var(--ok)}} .changes_requested{{color:var(--warn)}} .blocked,.error{{color:var(--bad)}}
li.blocker{{color:var(--bad)}} li.major{{color:var(--warn)}} .wrap{{overflow-x:auto}}
</style></head><body><main>
<h1>PR Triage Board</h1><div class="sub">{html.escape(repo)} · {len(reports)} open PRs · generated {now} by contribution-gatekeeper</div>
<div class="stats">
<div class="stat ready" data-f="ready"><b>{counts['ready']}</b>Ready</div>
<div class="stat changes_requested" data-f="changes_requested"><b>{counts['changes_requested']}</b>Changes requested</div>
<div class="stat blocked" data-f="blocked"><b>{counts['blocked']}</b>Blocked</div>
<div class="stat" data-f=""><b>{len(reports)}</b>All</div></div>
<div class="wrap"><table><thead><tr><th>PR</th><th>Project</th><th>Verdict</th><th>Score</th><th>Top issues</th></tr></thead>
<tbody>{''.join(rows)}</tbody></table></div>
<script>document.querySelectorAll('.stat').forEach(s=>s.onclick=()=>document.querySelectorAll('tbody tr').forEach(r=>r.style.display=!s.dataset.f||r.dataset.v===s.dataset.f?'':'none'))</script>
</main></body></html>"""


def dump(obj) -> str:
    return json.dumps(obj, indent=2, default=str)
