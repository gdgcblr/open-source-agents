"""Report and Artifact Generator for DevOps Migration Agent.

Generates all required documentation and machine-readable output:
- migration-report.md
- risk-assessment.md
- migration-checklist.md
- migration-summary.json
- validation-results.json
Ensures all reports strictly agree with the generated pipeline and parsed AST.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from models.github_workflow import GitHubWorkflow
from models.migration_report import (
    ActionMappingResult,
    ActionMappingStatus,
    MigrationSummary,
    TerraformAnalysisResult,
    ValidationResult,
)
from models.risk_model import RiskAssessment


def build_migration_summary(
    workflow: GitHubWorkflow,
    mappings: list[ActionMappingResult],
    risk: RiskAssessment,
    tf_result: TerraformAnalysisResult | None,
) -> MigrationSummary:
    """Builds a MigrationSummary model from workflow analysis."""
    direct_cnt = sum(1 for m in mappings if m.status == ActionMappingStatus.DIRECT)
    partial_cnt = sum(1 for m in mappings if m.status == ActionMappingStatus.PARTIAL)
    manual_cnt = sum(1 for m in mappings if m.status == ActionMappingStatus.MANUAL_MIGRATION)
    unsupported_cnt = sum(1 for m in mappings if m.status == ActionMappingStatus.UNSUPPORTED)
    unknown_cnt = sum(1 for m in mappings if m.status == ActionMappingStatus.UNKNOWN)

    # Estimate migration effort in engineer-hours
    effort = (
        (direct_cnt * 0.25)
        + (partial_cnt * 1.0)
        + (manual_cnt * 2.5)
        + (unsupported_cnt * 4.0)
        + (unknown_cnt * 2.0)
        + (len(workflow.detected_secrets) * 0.5)
        + (2.0 if tf_result and tf_result.has_terraform else 0.5)
    )

    return MigrationSummary(
        workflow_name=workflow.name,
        source_file=workflow.file_path,
        jobs_count=workflow.total_jobs,
        steps_count=workflow.total_steps,
        direct_mappings_count=direct_cnt,
        partial_mappings_count=partial_cnt,
        manual_mappings_count=manual_cnt,
        unsupported_count=unsupported_cnt,
        unknown_count=unknown_cnt,
        secrets_count=len(workflow.detected_secrets),
        risk_score=risk.overall_score,
        risk_level=risk.overall_level,
        has_terraform=bool(tf_result and tf_result.has_terraform),
        estimated_effort_hours=round(effort, 1),
        status="BLOCKED" if risk.blockers else "READY_FOR_REVIEW",
        generated_at=datetime.now(timezone.utc).isoformat(),
    )


def generate_migration_report_md(
    workflow: GitHubWorkflow,
    mappings: list[ActionMappingResult],
    summary: MigrationSummary,
    tf_result: TerraformAnalysisResult | None,
) -> str:
    """Generates comprehensive migration-report.md."""
    lines: list[str] = [
        f"# DevOps Migration Report: {workflow.name}",
        "",
        "> **Generated by Google ADK DevOps Migration Agent**  ",
        f"> **Timestamp:** `{summary.generated_at}` | **Source:** `{summary.source_file}`  ",
        f"> **Migration Readiness:** `{summary.status}` | **Estimated Effort:** `{summary.estimated_effort_hours} hours`",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        "",
        f"This report outlines the migration path for **{workflow.name}** from GitHub Actions to Azure DevOps Pipelines.",
        f"- **Total Jobs:** {summary.jobs_count}",
        f"- **Total Steps:** {summary.steps_count}",
        f"- **Direct Mappings:** {summary.direct_mappings_count}",
        f"- **Partial Mappings:** {summary.partial_mappings_count}",
        f"- **Manual Migrations Required:** {summary.manual_mappings_count}",
        f"- **Unsupported Actions:** {summary.unsupported_count}",
        f"- **Unknown/Custom Actions:** {summary.unknown_count}",
        f"- **Secrets Referenced:** {summary.secrets_count}",
        "",
        "---",
        "",
        "## 2. Action Compatibility Registry & Mapping Analysis",
        "",
        "| GitHub Action | Version | Target Azure DevOps Task / Directive | Mapping Status | Notes |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]

    for m in mappings:
        target = m.ado_task if m.ado_task else "*Manual Implementation*"
        notes = m.warnings[0] if m.warnings else m.explanation
        notes_sanitized = notes.replace("|", "\\|")
        lines.append(
            f"| `{m.action_name}` | `{m.action_version or 'latest'}` | `{target}` | **{m.status.value.upper()}** | {notes_sanitized} |"
        )

    lines.extend(
        [
            "",
            "---",
            "",
            "## 3. Triggers & Environment Translation",
            "",
            "### Workflow Triggers",
        ]
    )

    if workflow.triggers.push:
        branches = ", ".join(workflow.triggers.push.branches) or "all"
        lines.append(
            f"- **Push Trigger:** Included branches: `{branches}` -> `trigger.branches.include`"
        )
    else:
        lines.append("- **Push Trigger:** Disabled (`trigger: none`)")

    if workflow.triggers.pull_request:
        branches = ", ".join(workflow.triggers.pull_request.branches) or "all"
        lines.append(
            f"- **Pull Request Trigger:** Target branches: `{branches}` -> `pr.branches.include`"
        )
    else:
        lines.append("- **Pull Request Trigger:** Disabled (`pr: none`)")

    if workflow.triggers.schedule and workflow.triggers.schedule.cron:
        lines.append(
            f"- **Scheduled Cron:** `{', '.join(workflow.triggers.schedule.cron)}` -> `schedules` block"
        )

    if workflow.triggers.workflow_dispatch:
        lines.append("- **Manual Trigger:** Enabled via Azure Pipelines Manual Execution")

    lines.extend(
        [
            "",
            "### Runner Environments",
            "",
            "| GitHub Job ID | GitHub `runs-on` | Azure DevOps `vmImage` / Pool |",
            "| :--- | :--- | :--- |",
        ]
    )

    for jid, job in workflow.jobs.items():
        runs_on_str = str(job.runs_on)
        lines.append(f"| `{jid}` | `{runs_on_str}` | `vmImage: ubuntu-latest` |")

    lines.extend(
        [
            "",
            "---",
            "",
            "## 4. Secrets & Configuration Migration",
            "",
            "The following secret references were identified and must be established in Azure DevOps:",
            "",
            "| Secret Name | Recommended Azure DevOps Storage | Scope |",
            "| :--- | :--- | :--- |",
        ]
    )

    if workflow.detected_secrets:
        for sec in workflow.detected_secrets:
            lines.append(
                f"| `secrets.{sec}` | Azure Key Vault linked Variable Group (`$({sec})`) | Pipeline Secret |"
            )
    else:
        lines.append("| *(None detected)* | — | — |")

    if tf_result and tf_result.has_terraform:
        lines.extend(
            [
                "",
                "---",
                "",
                "## 5. Terraform & Infrastructure Integration",
                "",
                f"- **Discovered Files:** {tf_result.file_count} `.tf` configuration file(s)",
                f"- **Providers Identified:** {', '.join(tf_result.providers) or 'None'}",
                f"- **Remote Backend:** `{tf_result.backend_type or 'Local/None (Requires configuration)'}`",
                f"- **Resources Defined:** {tf_result.resources_count}",
                "- **Required Service Connections:**",
            ]
        )
        for sc in tf_result.service_connections_needed:
            lines.append(f"  - `{sc}`")
        if tf_result.findings:
            lines.append("- **Terraform Static Analysis Findings:**")
            for f in tf_result.findings:
                lines.append(f"  - {f}")

    lines.extend(
        [
            "",
            "---",
            "",
            "## 6. Manual Actions & Next Steps",
            "",
        ]
    )

    has_manual = False
    for m in mappings:
        if m.manual_steps:
            has_manual = True
            lines.append(f"### Remediating `{m.action_name}`")
            for step in m.manual_steps:
                lines.append(f"- {step}")
            lines.append("")

    if not has_manual:
        lines.append(
            "No manual action remediations required. All actions mapped directly or partially."
        )

    return "\n".join(lines)


def generate_risk_assessment_md(
    workflow: GitHubWorkflow,
    risk: RiskAssessment,
) -> str:
    """Generates detailed risk-assessment.md."""
    lines: list[str] = [
        f"# Migration Risk Assessment: {workflow.name}",
        "",
        "> **Quantitative Risk Evaluation**  ",
        f"> **Overall Score:** `{risk.overall_score}/100` | **Risk Rating:** **`{risk.overall_level.value}`**",
        "",
        "---",
        "",
        "## 1. Risk Evaluation Summary",
        "",
        risk.summary,
        "",
    ]

    if risk.blockers:
        lines.extend(
            [
                "### ⚠️ Deployment Blockers",
                "",
                "The following issues must be resolved before this pipeline can run in production:",
                "",
            ]
        )
        for b in risk.blockers:
            lines.append(f"- ⛔ **{b}**")
        lines.append("")

    lines.extend(
        [
            "---",
            "",
            "## 2. Category Breakdown",
            "",
            "| Category | Cumulative Score Impact | Risk Level |",
            "| :--- | :--- | :--- |",
        ]
    )

    for cat, score in risk.category_scores.items():
        cat_lvl = "HIGH" if score >= 25 else ("MEDIUM" if score >= 15 else "LOW")
        lines.append(f"| **{cat}** | `{score}` points | `{cat_lvl}` |")

    lines.extend(
        [
            "",
            "---",
            "",
            "## 3. Detailed Risk Factor Registry",
            "",
            "| Risk ID | Severity | Factor Title | Category | Remediation |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ]
    )

    for item in risk.items:
        remediation_sanitized = item.remediation.replace("|", "\\|")
        lines.append(
            f"| `{item.id}` | **{item.level.value}** | {item.title} | `{item.category.value}` | {remediation_sanitized} |"
        )

    lines.extend(
        [
            "",
            "---",
            "",
            "## 4. Pre-Production Sign-off Matrix",
            "",
            "- [ ] **Security Lead:** Verified secret redaction and least-privilege pipeline permissions.",
            "- [ ] **DevOps Lead:** Verified Azure DevOps Service Connection and agent pool capabilities.",
            "- [ ] **QA / Release Engineer:** Verified test execution equivalence in staging pipeline run.",
        ]
    )

    return "\n".join(lines)


def generate_migration_checklist_md(
    workflow: GitHubWorkflow,
    mappings: list[ActionMappingResult],
    summary: MigrationSummary,
) -> str:
    """Generates actionable migration-checklist.md."""
    lines: list[str] = [
        f"# DevOps Migration Checklist: {workflow.name}",
        "",
        "Follow this comprehensive checklist to execute, verify, and cut over to Azure DevOps.",
        "",
        "---",
        "",
        "## Phase 1: Pre-Migration & Azure DevOps Setup",
        "- [ ] Verify access to Azure DevOps Project and Organization.",
        "- [ ] Ensure agent pool permissions (`Hosted Ubuntu`, `Self-Hosted` if needed).",
        "- [ ] Install required Visual Studio Marketplace extensions (e.g. Terraform by Microsoft DevLabs).",
        "- [ ] Verify repository synchronization or mirror to Azure Repos / GitHub connection.",
        "",
        "## Phase 2: Service Connections & Secrets",
    ]

    if workflow.detected_secrets:
        for s in workflow.detected_secrets:
            lines.append(
                f"- [ ] Provision secret variable or KeyVault mapping for `secrets.{s}` -> `$({s})`."
            )
    else:
        lines.append("- [ ] Verify no secrets are required for initial build run.")

    if summary.has_terraform:
        lines.append(
            "- [ ] Configure AzureRM Service Connection in Project Settings > Service Connections."
        )
        lines.append("- [ ] Provision Azure Storage Account for Terraform remote state backend.")

    lines.extend(
        [
            "- [ ] Configure Docker Registry service connection if container build is performed.",
            "",
            "## Phase 3: Pipeline Import & Configuration",
            "- [ ] Copy `generated-pipeline.yml` to the repository root as `azure-pipelines.yml`.",
            "- [ ] Create new Azure Pipeline pointing to the repository file.",
            "- [ ] Configure pipeline triggers and branch policies on `main`.",
            "- [ ] Enable build validation status checks on Pull Requests.",
            "",
            "## Phase 4: Testing & Verification",
            "- [ ] Run pipeline manually on a feature branch (`feat/ado-migration-test`).",
            "- [ ] Confirm artifact publishing and caching steps succeed.",
            "- [ ] Compare build execution time and logs against GitHub Actions baseline.",
            "- [ ] Validate that secrets are masked properly in the pipeline console logs.",
            "",
            "## Phase 5: Cutover & Retirement",
            "- [ ] Disable or archive the original GitHub Actions workflow file.",
            "- [ ] Update branch protection rules to require the new Azure Pipeline status check.",
            "- [ ] Document pipeline operational procedures for team members.",
        ]
    )

    return "\n".join(lines)


def write_all_reports(
    output_dir: str | Path,
    workflow: GitHubWorkflow,
    mappings: list[ActionMappingResult],
    pipeline_yaml: str,
    validation: ValidationResult,
    risk: RiskAssessment,
    tf_result: TerraformAnalysisResult | None,
) -> dict[str, Path]:
    """Writes all 6 required deliverables to the output directory."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    summary = build_migration_summary(workflow, mappings, risk, tf_result)

    # 1. generated-pipeline.yml
    pipeline_path = out / "generated-pipeline.yml"
    pipeline_path.write_text(pipeline_yaml, encoding="utf-8")

    # 2. migration-report.md
    report_md = generate_migration_report_md(workflow, mappings, summary, tf_result)
    report_path = out / "migration-report.md"
    report_path.write_text(report_md, encoding="utf-8")

    # 3. risk-assessment.md
    risk_md = generate_risk_assessment_md(workflow, risk)
    risk_path = out / "risk-assessment.md"
    risk_path.write_text(risk_md, encoding="utf-8")

    # 4. migration-checklist.md
    checklist_md = generate_migration_checklist_md(workflow, mappings, summary)
    checklist_path = out / "migration-checklist.md"
    checklist_path.write_text(checklist_md, encoding="utf-8")

    # 5. migration-summary.json
    summary_path = out / "migration-summary.json"
    summary_path.write_text(summary.model_dump_json(indent=2), encoding="utf-8")

    # 6. validation-results.json
    validation_path = out / "validation-results.json"
    validation_path.write_text(validation.model_dump_json(indent=2), encoding="utf-8")

    return {
        "pipeline": pipeline_path,
        "report": report_path,
        "risk": risk_path,
        "checklist": checklist_path,
        "summary": summary_path,
        "validation": validation_path,
    }
