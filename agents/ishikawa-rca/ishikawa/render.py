"""Render an RCAReport as Markdown with a Mermaid fishbone (renders natively on GitHub)."""

from __future__ import annotations

from .schema import CATEGORIES, RCAReport

_ICON = {"root_cause": "🎯", "contributing": "⚠️", "refuted": "❌", "inconclusive": "❔"}


def _esc(text: str) -> str:
    return text.replace('"', "'").replace("\n", " ")[:70]


def fishbone_mermaid(report: RCAReport) -> str:
    lines = ["flowchart LR", f'  EFFECT(["{_esc(report.effect)}"]):::effect']
    for cat in CATEGORIES:
        lines.append(f'  {cat}["{cat.upper()}"]:::bone --> EFFECT')
        for i, cause in enumerate(c for c in report.causes if c.category == cat):
            node = f"{cat}{i}"
            lines.append(f'  {node}["{_ICON[cause.verdict]} {_esc(cause.description)}"]:::{cause.verdict} --> {cat}')
    lines += [
        "  classDef effect fill:#1f2937,color:#fff,stroke:#ef4444,stroke-width:3px",
        "  classDef bone fill:#e5e7eb,color:#111,stroke:#6b7280",
        "  classDef root_cause fill:#fee2e2,color:#7f1d1d,stroke:#dc2626,stroke-width:3px",
        "  classDef contributing fill:#fef3c7,color:#78350f,stroke:#d97706",
        "  classDef refuted fill:#f3f4f6,color:#6b7280,stroke:#d1d5db,stroke-dasharray:4",
        "  classDef inconclusive fill:#eef2ff,color:#3730a3,stroke:#818cf8",
    ]
    return "\n".join(lines)


def to_markdown(report: RCAReport, elapsed_s: float | None = None,
                guardrails: dict | None = None, metrics: dict | None = None) -> str:
    out = [f"# RCA: {report.incident_title}", ""]
    if metrics:
        out += [f"_Generated by Ishikawa in {metrics['elapsed_s']}s · {metrics['llm_calls']} model calls · "
                f"est. ${metrics['est_cost_usd']:.3f} · ~{metrics['minutes_saved']:.0f} engineer-minutes saved "
                f"vs a {metrics['manual_baseline_min']:.0f}-minute manual baseline_", ""]
    elif elapsed_s is not None:
        out += [f"_Generated by Ishikawa in {elapsed_s}s_", ""]
    if guardrails:
        label = "✅ Ready for approval" if guardrails["decision"] == "ready_for_approval" else "🛑 Needs human review"
        out += [f"**Guardrail decision:** {label}", ""]
    out += [
        f"**Effect:** {report.effect}", "",
        f"**Root cause:** {report.root_cause}", "",
        f"**Culprit:** `{report.culprit}`", "",
        f"**Immediate fix:** `{report.immediate_fix}`", "",
        "## Fishbone", "", "```mermaid", fishbone_mermaid(report), "```", "",
        "## Hypotheses examined", "",
        "| Verdict | Category | Hypothesis | Confidence | Evidence |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]
    order = {"root_cause": 0, "contributing": 1, "inconclusive": 2, "refuted": 3}
    for c in sorted(report.causes, key=lambda c: order[c.verdict]):
        ev = "<br>".join(e.replace("|", "\\|") for e in c.evidence)
        desc = c.description.replace("|", "\\|")
        out.append(f"| {_ICON[c.verdict]} {c.verdict} | {c.category} | {desc} | {c.confidence:.0%} | {ev} |")
    out += ["", "## 5 Whys", ""] + [f"{i}. {w}" for i, w in enumerate(report.five_whys, 1)]
    out += ["", "## Corrective actions", ""] + [f"- [ ] {a}" for a in report.corrective_actions]
    out += ["", "## Preventive actions", ""] + [f"- [ ] {a}" for a in report.preventive_actions]
    if guardrails:
        out += ["", "## Guardrails", "", "| Check | Result | Detail |", "| :--- | :--- | :--- |"]
        out += [f"| {c['name']} | {'pass' if c['passed'] else 'FAIL'} | {str(c['detail']).replace('|', chr(92) + '|')} |"
                for c in guardrails["checks"]]
        fix = guardrails["fix_policy"]
        if not fix["allowed"]:
            out += ["", f"The model proposed `{fix['original'].replace('`', '')}`; it was blocked ({fix['reason']}) "
                        f"and replaced with a data-derived rollback."]
        if guardrails["redactions"]:
            out += ["", "Redacted before reaching the model: " +
                    ", ".join(f"{k} ×{n}" for k, n in guardrails["redactions"].items())]
        if guardrails["injections"]:
            out += ["", f"Quarantined {len(guardrails['injections'])} prompt-injection attempt(s) from: " +
                    ", ".join(sorted({i['tool'] for i in guardrails['injections']}))]
    return "\n".join(out) + "\n"
