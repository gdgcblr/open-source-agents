/**
 * Output formatters: JSON and Markdown.
 *
 * Security invariants:
 *  - ALL file-derived strings are HTML-escaped when embedded in Markdown.
 *  - ALL model text is HTML-escaped.
 *  - No raw secret content is ever passed here (scanner guarantees redaction).
 */

import type { AuditResult, Finding, AiAnnotation } from "./types.js";

// ---------------------------------------------------------------------------
// HTML / Markdown escape
// ---------------------------------------------------------------------------

/**
 * Escape characters with special meaning in HTML/Markdown.
 * Applied to ALL external-derived strings in Markdown output.
 */
export function escapeMarkdown(raw: string): string {
  return raw
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/\|/g, "\\|") // table cell separator
    .replace(/`/g, "&#96;"); // backtick
}

// ---------------------------------------------------------------------------
// JSON output
// ---------------------------------------------------------------------------

export function formatJson(result: AuditResult): string {
  return JSON.stringify(result, null, 2);
}

// ---------------------------------------------------------------------------
// Markdown output
// ---------------------------------------------------------------------------

const SEVERITY_EMOJI: Record<string, string> = {
  high: "🔴",
  medium: "🟡",
  low: "🔵",
  info: "⚪",
};

export function formatMarkdown(result: AuditResult): string {
  const lines: string[] = [];

  lines.push("# Contribution Readiness Audit Report");
  lines.push("");
  lines.push(`**Target:** \`${escapeMarkdown(result.targetDir)}\``);
  lines.push(`**Generated:** ${escapeMarkdown(result.timestamp)}`);

  if (result.truncated) {
    lines.push("");
    lines.push(
      `> ⚠️ **Scan truncated:** ${escapeMarkdown(result.truncationReason ?? "unknown reason")}`
    );
  }

  lines.push("");

  const highCount = result.findings.filter((f) => f.severity === "high").length;
  const mediumCount = result.findings.filter((f) => f.severity === "medium").length;
  const lowCount = result.findings.filter((f) => f.severity === "low").length;
  const infoCount = result.findings.filter((f) => f.severity === "info").length;

  const overallStatus = highCount > 0 ? "❌ FAIL" : "✅ PASS";
  lines.push(`## Summary — ${overallStatus}`);
  lines.push("");
  lines.push(`| Severity | Count |`);
  lines.push(`|----------|-------|`);
  lines.push(`| 🔴 High  | ${highCount} |`);
  lines.push(`| 🟡 Medium | ${mediumCount} |`);
  lines.push(`| 🔵 Low   | ${lowCount} |`);
  lines.push(`| ⚪ Info  | ${infoCount} |`);
  lines.push(`| **Total** | **${result.findings.length}** |`);
  lines.push("");

  if (result.findings.length === 0) {
    lines.push("_No findings. Great job!_");
  } else {
    lines.push("## Findings");
    lines.push("");
    lines.push("| ID | Severity | Rule | Description | File | Line | Label | Evidence |");
    lines.push("|:---|:--------|:-----|:------------|:-----|-----:|:------|:---------|");

    for (const f of result.findings) {
      const emoji = SEVERITY_EMOJI[f.severity] ?? "";
      const desc = escapeMarkdown(f.description);
      const file = escapeMarkdown(f.file);
      const evidence = escapeMarkdown(f.evidence);
      lines.push(
        `| ${f.id} | ${emoji} ${f.severity} | ${f.rule} | ${desc} | \`${file}\` | ${f.line || "—"} | ${f.label} | ${evidence} |`
      );
    }
  }

  // AI annotations section
  if (result.annotations.length > 0) {
    lines.push("");
    lines.push("## AI Explanations");
    lines.push(
      "_Generated by AI. Not authoritative — used for context only. Findings above are deterministic._"
    );
    lines.push("");

    const annotationMap = new Map<string, AiAnnotation>();
    for (const a of result.annotations) {
      annotationMap.set(a.findingId, a);
    }

    for (const f of result.findings) {
      const ann = annotationMap.get(f.id);
      if (ann) {
        lines.push(`### ${f.id} — ${escapeMarkdown(f.rule)}`);
        lines.push(`> ${escapeMarkdown(ann.text)}`);
        lines.push("");
      }
    }
  }

  lines.push("---");
  lines.push("_Audit generated by [repo-contribution-auditor](https://github.com/gdgcblr/open-source-agents/tree/main/agents/repo-contribution-auditor)_");

  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Determine exit code
// ---------------------------------------------------------------------------

export function determineExitCode(findings: Finding[]): number {
  const hasHigh = findings.some((f) => f.severity === "high");
  return hasHigh ? 1 : 0;
}
