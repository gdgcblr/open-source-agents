"""Run the labelled eval cases through the deterministic gatekeeper.

    .venv/bin/python evals/run_evals.py

Each case is committed on a branch of a throwaway upstream-like repo, loaded
with source.load_local() and checked with run_static() (exactly what the
offline ADK pipeline does, minus the Markdown rendering). Prints a table and
per-check precision/recall, writes evals/RESULTS.md, and exits non-zero if any
case is wrong.

Only check ids are reported, never finding messages: messages can quote the
payload that triggered them, and RESULTS.md lives inside the project folder.
"""

from __future__ import annotations

import shutil
import sys
import tempfile
import time
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from cases import CASES  # noqa: E402  (also puts tests/ on sys.path)
import testkit  # noqa: E402
from mergewarden.checks import run_static  # noqa: E402
from mergewarden.models import Report, Severity  # noqa: E402


def run() -> tuple[list[dict], dict[str, Counter]]:
    tmp = Path(tempfile.mkdtemp(prefix="gatekeeper-evals-"))
    rows, per_check = [], {}
    try:
        repo = testkit.build_upstream(tmp / "repo")
        for i, case in enumerate(CASES):
            sub, policy = testkit.contribute(repo, case.files(), workdir=tmp / f"work{i}", force=case.force,
                                             project=case.project, body=case.body)
            findings = run_static(sub, policy)
            got = {f.check for f in findings if f.severity.rank >= Severity.MINOR.rank}
            verdict = Report(sub, findings).verdict.value
            for check in got | case.checks:
                c = per_check.setdefault(check, Counter())
                c["tp" if check in got and check in case.checks else "fp" if check in got else "fn"] += 1
            rows.append({"case": case.name, "description": case.description,
                         "expected": case.verdict, "got": verdict,
                         "expected_checks": case.checks, "got_checks": got,
                         "pass": verdict == case.verdict and got == case.checks})
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return rows, per_check


def _ratio(a: int, b: int) -> str:
    return f"{a / b:.2f}" if b else "n/a"


def table(rows: list[dict], per_check: dict[str, Counter]) -> tuple[str, str, str]:
    case_lines = ["| case | expected | got | checks (got) | pass |", "| :--- | :--- | :--- | :--- | :---: |"]
    for r in rows:
        extra = sorted(r["got_checks"] - r["expected_checks"])
        missed = sorted(r["expected_checks"] - r["got_checks"])
        note = ", ".join(sorted(r["got_checks"])) or "—"
        if extra:
            note += f" (unexpected: {', '.join(extra)})"
        if missed:
            note += f" (missed: {', '.join(missed)})"
        case_lines.append(f"| {r['case']} | {r['expected']} | {r['got']} | {note} | {'✅' if r['pass'] else '❌'} |")
    check_lines = ["| check id | TP | FP | FN | precision | recall |", "| :--- | ---: | ---: | ---: | ---: | ---: |"]
    for check in sorted(per_check):
        c = per_check[check]
        check_lines.append(f"| `{check}` | {c['tp']} | {c['fp']} | {c['fn']} | "
                           f"{_ratio(c['tp'], c['tp'] + c['fp'])} | {_ratio(c['tp'], c['tp'] + c['fn'])} |")
    verdict_ok = sum(r["expected"] == r["got"] for r in rows)
    exact_ok = sum(r["pass"] for r in rows)
    summary = (f"Verdict accuracy: {verdict_ok}/{len(rows)} ({100 * verdict_ok / len(rows):.0f}%)  ·  "
               f"Exact check-set match: {exact_ok}/{len(rows)} ({100 * exact_ok / len(rows):.0f}%)")
    return "\n".join(case_lines), "\n".join(check_lines), summary


def main() -> int:
    t0 = time.time()
    rows, per_check = run()
    cases_md, checks_md, summary = table(rows, per_check)
    print(cases_md, "", checks_md, "", summary, sep="\n")
    descriptions = "\n".join(f"- **{r['case']}**: {r['description']}" for r in rows)
    (HERE / "RESULTS.md").write_text(
        "# Gatekeeper eval results\n\n"
        f"Generated by `python evals/run_evals.py` in {time.time() - t0:.1f}s "
        "(deterministic checks only, no LLM). A case passes when both the verdict and the exact set of "
        "check ids at severity minor or above match the label.\n\n"
        f"**{summary}**\n\n## Cases\n\n{cases_md}\n\n## Per-check precision / recall\n\n{checks_md}\n\n"
        f"## Case descriptions\n\n{descriptions}\n",
        encoding="utf-8",
    )
    print(f"\nWrote {HERE / 'RESULTS.md'}")
    return 0 if all(r["pass"] for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
