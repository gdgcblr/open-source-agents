"""Running README steps in a fresh sandbox: a Docker container or a throwaway local venv.

Every step runs in one bash process, the way a newcomer types commands into one terminal, so
cd, source and export carry over between steps. Steps are separated by marker lines that only
FirstRun prints, and the log is split back into per-step results afterwards.
"""

from __future__ import annotations

import os
import queue
import re
import secrets
import shutil
import signal
import subprocess
import sys
import tempfile
import threading
import time
from pathlib import Path
from typing import Callable, Optional

from .models import EventFn, RunResult, Step, StepResult, noop_event
from .repair import copy_project

MARK_PREFIX = "@@FR-"
MAX_STEP_OUTPUT = 200_000
ENV_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

DEFAULT_IMAGE = "python:3.12-slim"
NODE_IMAGE = "node:22-bookworm-slim"
# Official Debian based images, where adding git with apt is safe and cheap
DEBIAN_BASE_RE = re.compile(r"^(?:docker\.io/)?(?:library/)?(?:python|node):[\w.-]+$")
ENV_IMAGE_VERSION = "v1"
# A newcomer always has git (they cloned the repo), slim images do not
GIT_DOCKERFILE = """FROM {base}
RUN apt-get update \\
 && apt-get install -y --no-install-recommends git ca-certificates \\
 && rm -rf /var/lib/apt/lists/*
"""
NODE_INSTALL = "apt-get update && apt-get install -y --no-install-recommends nodejs npm"
NODE_CMD_RE = re.compile(r"(?:^|&&|\|\||;|\n)\s*(?:sudo\s+)?(?:npm|npx|node|yarn|pnpm|corepack)\b")
PYTHON_CMD_RE = re.compile(r"(?:^|&&|\|\||;|\n)\s*(?:sudo\s+)?(?:python3?|pip3?|uv|poetry|pipx)\b")
PYTHON_MANIFESTS = ("pyproject.toml", "setup.py", "setup.cfg", "Pipfile")

# @@MARK@@ is replaced with the per-run marker. Kept bash 3.2 safe because macOS still ships it.
RUN_HEADER = r"""#!/usr/bin/env bash
# Generated by FirstRun. Runs the README steps in one shell, like a person at a terminal.
exec 2>&1 </dev/null
__fr_mark() { printf '\n%s %s\n' '@@MARK@@' "$*"; }

# a step that calls exit kills this shell, so report how it ended on the way out
__fr_cur=0
__fr_on_exit() {
  __fr_x=$?
  if [ "$__fr_cur" != 0 ]; then __fr_mark end "$__fr_cur" "$__fr_x"; fi
}
trap __fr_on_exit EXIT

# servers and UIs never exit on their own: run them in their own process group and count
# them as working if they are still up after the watch window
__fr_watch() {
  set -m
  ( . "$FR_STATE/step_$1.sh" ) &
  __fr_pid=$!
  set +m
  echo "$__fr_pid" >> "$FR_STATE/pgids"
  __fr_ticks=0
  while kill -0 "$__fr_pid" 2>/dev/null; do
    if [ "$__fr_ticks" -ge $(( $2 * 4 )) ]; then
      __fr_mark alive "$1"
      : > "$FR_STATE/alive_$1"
      # disown first, otherwise bash prints a "Terminated" job notice into the log
      disown "$__fr_pid" 2>/dev/null
      kill -TERM -- "-$__fr_pid" 2>/dev/null
      sleep 1
      kill -KILL -- "-$__fr_pid" 2>/dev/null
      return 0
    fi
    sleep 0.25
    __fr_ticks=$(( __fr_ticks + 1 ))
  done
  wait "$__fr_pid"
}

cd "$FR_WORKDIR" || { echo "FirstRun: cannot enter $FR_WORKDIR"; exit 97; }
"""


def build_script(steps: list[Step], token: str, watch_seconds: int) -> dict[str, str]:
    mark = MARK_PREFIX + token
    parts = [RUN_HEADER.replace("@@MARK@@", mark)]
    for s in steps:
        n = s.index
        call = f"__fr_watch {n} {int(watch_seconds)}" if s.long_running else f'. "$FR_STATE/step_{n}.sh"'
        ok = '[ "$__fr_rc" -eq 0 ]'
        if s.expect_exit:
            ok = f'{{ [ "$__fr_rc" -eq 0 ] || [ "$__fr_rc" -eq {int(s.expect_exit)} ]; }}'
        parts.append(
            f"__fr_cur={n}; __fr_mark begin {n}\n"
            f"{call}\n"
            f'__fr_rc=$?; __fr_cur=0; __fr_mark end {n} "$__fr_rc"\n'
            f"{ok} || exit 0\n"
        )
    parts.append("__fr_mark done\nexit 0\n")
    files = {"run.sh": "\n".join(parts)}
    for s in steps:
        files[f"step_{s.index}.sh"] = s.command.rstrip("\n") + "\n"
    return files


class _Splitter:
    """Turns raw output lines into ("line", text) and ("mark", kind, args) items.

    Markers are printed with a leading newline so they always start a line. That newline shows
    up as one extra blank line before the marker when the output already ended cleanly, so a
    single blank line right before a marker is dropped.
    """

    def __init__(self, token: str):
        self.marker = re.compile(rf"^{re.escape(MARK_PREFIX + token)} (begin|end|alive|done)(?: (.*))?$")
        self.pending_blank = False

    def feed(self, line: str) -> list[tuple]:
        line = line.rstrip("\r\n")
        m = self.marker.match(line)
        if m:
            self.pending_blank = False
            return [("mark", m.group(1), (m.group(2) or "").split())]
        out = []
        if self.pending_blank:
            out.append(("line", ""))
            self.pending_blank = False
        if line == "":
            self.pending_blank = True
        else:
            out.append(("line", line))
        return out

    def flush(self) -> list[tuple]:
        if self.pending_blank:
            self.pending_blank = False
            return [("line", "")]
        return []


def _ints(args: list[str]) -> list[int]:
    out = []
    for a in args:
        try:
            out.append(int(a))
        except ValueError:
            break
    return out


def _echo(command: str) -> list[str]:
    lines = command.rstrip("\n").splitlines() or [""]
    return [f"$ {lines[0]}"] + [f"> {line}" for line in lines[1:]]


def _tail(text: str, limit: int = MAX_STEP_OUTPUT) -> str:
    if len(text) <= limit:
        return text
    return "[... output trimmed ...]\n" + text[-limit:]


def parse_log(raw: str, steps: list[Step], token: str,
              durations: Optional[dict[int, float]] = None) -> tuple[list[StepResult], str]:
    """Split a raw sandbox log into per-step results plus a readable log without markers.

    A step that began but never printed its end marker comes back as failed with exit_code
    None; the caller decides whether that was a timeout or the shell dying.
    """
    durations = durations or {}
    by_index = {s.index: s for s in steps}
    splitter = _Splitter(token)
    outputs: dict[int, list[str]] = {}
    ended: dict[int, int] = {}
    alive: set[int] = set()
    clean: list[str] = []
    current: Optional[int] = None

    def add(line: str) -> None:
        clean.append(line)
        if current is not None:
            outputs[current].append(line)

    items = [item for line in raw.splitlines() for item in splitter.feed(line)]
    items += splitter.flush()
    for item in items:
        if item[0] == "line":
            add(item[1])
            continue
        _, kind, args = item
        nums = _ints(args)
        if kind == "begin" and nums:
            current = nums[0]
            outputs[current] = []
            if current in by_index:
                clean.extend(_echo(by_index[current].command))
        elif kind == "end" and len(nums) >= 2:
            ended[nums[0]] = nums[1]
            current = None
        elif kind == "alive" and nums:
            alive.add(nums[0])

    results = []
    for s in steps:
        n = s.index
        out = _tail("\n".join(outputs.get(n, [])).strip("\n"))
        took = round(durations.get(n, 0.0), 2)
        if n in ended:
            rc = ended[n]
            if rc == 0:
                status, code = ("alive", None) if n in alive else ("passed", 0)
            elif s.expect_exit and rc == s.expect_exit:
                status, code = "passed", rc
            else:
                status, code = "failed", rc
            results.append(StepResult(s, status, code, out, took))
        elif n in outputs:
            results.append(StepResult(s, "failed", None, out, took))
        else:
            results.append(StepResult(s, "not_run", None, "", 0.0))
    return results, "\n".join(clean)


class _Collector:
    """Watches output as it streams: emits events and keeps the raw lines for parse_log."""

    def __init__(self, steps: list[Step], token: str, on_event: EventFn):
        self.steps = {s.index: s for s in steps}
        self.on_event = on_event
        self.splitter = _Splitter(token)
        self.raw: list[str] = []
        self.starts: dict[int, float] = {}
        self.durations: dict[int, float] = {}
        self.alive: set[int] = set()

    def handle(self, line: str) -> None:
        line = line.rstrip("\r\n")
        self.raw.append(line)
        self._dispatch(self.splitter.feed(line))

    def finish(self) -> tuple[str, dict[int, float]]:
        self._dispatch(self.splitter.flush())
        now = time.monotonic()
        for n, t in self.starts.items():
            self.durations.setdefault(n, now - t)
        return "\n".join(self.raw), self.durations

    def _dispatch(self, items: list[tuple]) -> None:
        for item in items:
            if item[0] == "line":
                self.on_event("log", item[1], None)
                continue
            _, kind, args = item
            nums = _ints(args)
            if kind == "begin" and nums:
                n = nums[0]
                self.starts[n] = time.monotonic()
                cmd = self.steps[n].command if n in self.steps else ""
                self.on_event("step_start", "\n".join(_echo(cmd)), {"index": n, "command": cmd})
            elif kind == "alive" and nums:
                self.alive.add(nums[0])
            elif kind == "end" and len(nums) >= 2:
                n, rc = nums[0], nums[1]
                self.durations[n] = time.monotonic() - self.starts.get(n, time.monotonic())
                step = self.steps.get(n)
                if rc == 0:
                    status, code = ("alive", None) if n in self.alive else ("passed", 0)
                elif step is not None and step.expect_exit and rc == step.expect_exit:
                    status, code = "passed", rc
                else:
                    status, code = "failed", rc
                self.on_event("step_end", f"step {n} {status}", {"index": n, "status": status, "exit_code": code})


def _pump(stream, q: queue.Queue) -> None:
    try:
        for chunk in iter(stream.readline, b""):
            q.put(chunk.decode("utf-8", errors="replace"))
    except (OSError, ValueError):
        pass
    finally:
        q.put(None)


def _stream(cmd: list[str], *, on_line: Callable[[str], None], deadline: float,
            kill: Callable[[subprocess.Popen], None], **popen_kwargs) -> tuple[Optional[int], bool, subprocess.Popen]:
    """Run cmd, feeding each output line to on_line, and kill it if the deadline passes."""
    proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, **popen_kwargs)
    q: queue.Queue = queue.Queue()
    threading.Thread(target=_pump, args=(proc.stdout, q), daemon=True).start()
    timed_out = False
    try:
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                timed_out = True
                kill(proc)
                break
            try:
                item = q.get(timeout=min(remaining, 0.5))
            except queue.Empty:
                continue
            if item is None:
                break
            on_line(item)
        if timed_out:
            # pick up whatever was printed before the kill landed
            grace = time.monotonic() + 3
            while time.monotonic() < grace:
                try:
                    item = q.get(timeout=0.2)
                except queue.Empty:
                    continue
                if item is None:
                    break
                on_line(item)
    except BaseException:
        kill(proc)
        raise
    try:
        rc = proc.wait(timeout=10)
    except subprocess.TimeoutExpired:
        proc.kill()
        rc = proc.wait()
    return rc, timed_out, proc


class Sandbox:
    name = "sandbox"
    watch_seconds = 20

    def available(self) -> tuple[bool, str]:
        raise NotImplementedError

    def describe(self) -> str:
        return self.name

    def run(self, project_dir: Path, steps: list[Step], *, env: Optional[dict[str, str]] = None,
            label: str = "as documented", on_event: EventFn = noop_event,
            timeout: int = 900) -> RunResult:
        raise NotImplementedError

    def _error(self, label: str, steps: list[Step], started: float, message: str) -> RunResult:
        return RunResult(
            label=label, status="error",
            results=[StepResult(s, "not_run", None, "", 0.0) for s in steps],
            duration=round(time.monotonic() - started, 2), sandbox=self.describe(), log="",
            error=message,
        )

    def _build(self, label: str, steps: list[Step], token: str, collector: _Collector,
               rc: Optional[int], timed_out: bool, started: float) -> RunResult:
        raw, durations = collector.finish()
        results, log = parse_log(raw, steps, token, durations)
        error = None
        for r in results:
            if r.status == "failed" and r.exit_code is None:
                if timed_out:
                    r.status = "timeout"
                elif rc is not None:
                    # Popen reports death by signal as a negative number, shells say 128 + n
                    r.exit_code = rc if rc >= 0 else 128 - rc
        if timed_out:
            status = "timeout"
        elif any(r.status == "failed" for r in results):
            status = "failed"
        elif all(r.ok for r in results):
            status = "passed"
        else:
            status = "error"
            error = f"the sandbox stopped before running every step (exit code {rc})"
            if log.strip():
                error += f": {log.strip().splitlines()[-1]}"
        return RunResult(label=label, status=status, results=results,
                         duration=round(time.monotonic() - started, 2), sandbox=self.describe(),
                         log=log, error=error)

    @staticmethod
    def _write_state(state: Path, steps: list[Step], token: str, watch_seconds: int) -> None:
        state.mkdir(parents=True, exist_ok=True)
        for name, content in build_script(steps, token, watch_seconds).items():
            (state / name).write_text(content, encoding="utf-8")


class LocalSandbox(Sandbox):
    """A temp copy of the project plus a brand new venv on this machine.

    Not isolated like a container: commands run as you, with your filesystem. The environment
    is rebuilt from scratch though, so nothing from your shell (keys, PATH, installed packages)
    leaks in.
    """

    name = "local"

    def __init__(self, python: str = sys.executable, watch_seconds: int = 20,
                 pip_cache: Optional[Path] = None):
        self.python = python
        self.watch_seconds = watch_seconds
        self.pip_cache = pip_cache or Path.home() / ".cache" / "firstrun" / "pip"
        self._version: Optional[str] = None

    def available(self) -> tuple[bool, str]:
        if not shutil.which("bash"):
            return False, "bash is not installed"
        if not (Path(self.python).exists() or shutil.which(self.python)):
            return False, f"python interpreter not found: {self.python}"
        return True, ""

    def describe(self) -> str:
        if self._version is None:
            try:
                self._version = subprocess.run(
                    [self.python, "-c", "import platform; print(platform.python_version())"],
                    capture_output=True, text=True, timeout=20,
                ).stdout.strip() or "?"
            except (OSError, subprocess.SubprocessError):
                self._version = "?"
        return f"local venv (python {self._version})"

    def _env(self, venv: Path, home: Path, work: Path, state: Path, user_env: dict[str, str]) -> dict[str, str]:
        self.pip_cache.mkdir(parents=True, exist_ok=True)
        env = {
            "PATH": f"{venv / 'bin'}:{self._system_path()}",
            "HOME": str(home),
            "VIRTUAL_ENV": str(venv),
            "LANG": "en_US.UTF-8",
            "TERM": "dumb",
            "PYTHONUNBUFFERED": "1",
            "PYTHONNOUSERSITE": "1",
            "PIP_DISABLE_PIP_VERSION_CHECK": "1",
            "PIP_DEFAULT_TIMEOUT": "60",
            "PIP_CACHE_DIR": str(self.pip_cache),
        }
        env.update({k: v for k, v in user_env.items() if ENV_KEY.match(k)})
        env["FR_WORKDIR"] = str(work)
        env["FR_STATE"] = str(state)
        return env

    @staticmethod
    def _system_path() -> str:
        base = "/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
        brew = "/opt/homebrew/bin"
        missing = any(shutil.which(tool, path=base) is None for tool in ("node", "git"))
        if missing and os.path.isdir(brew):
            # after the system dirs, so the venv and system tools still win
            base += ":" + brew
        return base

    @staticmethod
    def _kill_all(proc: subprocess.Popen, state: Path) -> None:
        groups = {proc.pid}
        try:
            groups |= {int(x) for x in (state / "pgids").read_text().split() if x.isdigit()}
        except OSError:
            pass
        for g in groups:
            try:
                os.killpg(g, signal.SIGKILL)
            except (ProcessLookupError, PermissionError, OSError):
                pass

    def run(self, project_dir: Path, steps: list[Step], *, env: Optional[dict[str, str]] = None,
            label: str = "as documented", on_event: EventFn = noop_event,
            timeout: int = 900) -> RunResult:
        started = time.monotonic()
        ok, reason = self.available()
        if not ok:
            return self._error(label, steps, started, reason)
        token = secrets.token_hex(6)
        tmp = Path(tempfile.mkdtemp(prefix="firstrun-"))
        try:
            work = copy_project(Path(project_dir), tmp / "work")
            state, home, venv = tmp / "state", tmp / "home", tmp / "venv"
            home.mkdir()
            self._write_state(state, steps, token, self.watch_seconds)
            on_event("info", "Creating a fresh virtual environment", None)
            try:
                made = subprocess.run([self.python, "-m", "venv", str(venv)],
                                      capture_output=True, text=True, timeout=300)
            except (OSError, subprocess.SubprocessError) as exc:
                return self._error(label, steps, started, f"could not create a virtual environment: {exc}")
            if made.returncode != 0:
                detail = (made.stderr or made.stdout).strip()[-500:]
                return self._error(label, steps, started, f"could not create a virtual environment: {detail}")

            run_env = self._env(venv, home, work, state, env or {})
            bash = shutil.which("bash", path=run_env["PATH"]) or "bash"
            collector = _Collector(steps, token, on_event)
            proc = None
            try:
                rc, timed_out, proc = _stream(
                    [bash, str(state / "run.sh")], on_line=collector.handle,
                    deadline=time.monotonic() + timeout,
                    kill=lambda p: self._kill_all(p, state),
                    cwd=str(work), env=run_env, start_new_session=True,
                )
            finally:
                if proc is not None:
                    self._kill_all(proc, state)  # anything the steps left running in the background
            return self._build(label, steps, token, collector, rc, timed_out, started)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


class DockerSandbox(Sandbox):
    """A throwaway container per run. The project is copied in, never bind mounted."""

    name = "docker"

    def __init__(self, image: str = DEFAULT_IMAGE, memory: str = "2g", cpus: str = "2",
                 pids_limit: int = 512, pip_cache_volume: str = "firstrun-pip-cache",
                 watch_seconds: int = 20, with_git: bool = True):
        self.image = image
        self.memory = memory
        self.cpus = cpus
        self.pids_limit = pids_limit
        self.pip_cache_volume = pip_cache_volume
        self.watch_seconds = watch_seconds
        self.with_git = with_git
        self._run_image: Optional[str] = None  # what containers actually start from
        self._git_failed_for: Optional[str] = None  # base whose git layer could not be built

    def _wants_git(self) -> bool:
        return self.with_git and bool(DEBIAN_BASE_RE.match(self.image)) and self._git_failed_for != self.image

    def describe(self) -> str:
        if self._run_image and self._run_image != self.image:
            return f"docker {self.image} + git"
        if self._run_image is None and self._wants_git():
            return f"docker {self.image} + git"
        return f"docker {self.image}"

    @staticmethod
    def env_tag(base: str) -> str:
        """Local tag of the cached base + git image, e.g. firstrun-env:python-3.12-slim-v1."""
        name = re.sub(r"^(?:docker\.io/)?(?:library/)?", "", base.lower())
        name = re.sub(r"[^a-z0-9_.-]+", "-", name).strip("-.")
        return f"firstrun-env:{name}-{ENV_IMAGE_VERSION}"

    @staticmethod
    def _docker(*args: str, timeout: int = 120, input: Optional[str] = None) -> subprocess.CompletedProcess:
        return subprocess.run(["docker", *args], capture_output=True, text=True, timeout=timeout,
                              input=input)

    @staticmethod
    def _last_line(p: subprocess.CompletedProcess) -> str:
        lines = (p.stderr or p.stdout or "").strip().splitlines()
        return lines[-1] if lines else "unknown error"

    def available(self) -> tuple[bool, str]:
        try:
            p = self._docker("info", "--format", "{{.ServerVersion}}", timeout=20)
        except FileNotFoundError:
            return False, "docker is not installed (or not on PATH)"
        except subprocess.TimeoutExpired:
            return False, "docker did not answer within 20 seconds"
        if p.returncode != 0:
            return False, f"the docker daemon is not reachable: {self._last_line(p)}"
        return True, ""

    def _ensure_base(self, on_event: EventFn) -> Optional[str]:
        if self._docker("image", "inspect", self.image, timeout=30).returncode == 0:
            return None
        on_event("info", f"Pulling {self.image} (only needed the first time)", None)
        try:
            p = self._docker("pull", self.image, timeout=1200)
        except subprocess.TimeoutExpired:
            return f"pulling {self.image} took too long"
        if p.returncode != 0:
            return f"could not pull {self.image}: {self._last_line(p)}"
        return None

    def _ensure_image(self, on_event: EventFn) -> Optional[str]:
        """Pick the image containers start from. Returns a problem message or None."""
        if not self._wants_git():
            self._run_image = self.image
            return self._ensure_base(on_event)
        tag = self.env_tag(self.image)
        if self._docker("image", "inspect", tag, timeout=30).returncode == 0:
            self._run_image = tag
            return None
        problem = self._ensure_base(on_event)
        if problem:
            return problem
        on_event("info", "Preparing a fresh image with git (one time)", None)
        try:
            p = self._docker("build", "-t", tag, "-", timeout=900,
                             input=GIT_DOCKERFILE.format(base=self.image))
            failure = None if p.returncode == 0 else self._last_line(p)
        except subprocess.TimeoutExpired:
            failure = "the build took too long"
        if failure:
            # flaky network at an event is normal, a plain image is still a fair test
            self._git_failed_for = self.image
            self._run_image = self.image
            on_event("warn", f"Could not add git to {self.image} ({failure}), using the plain image", None)
            return None
        self._run_image = tag
        return None

    @staticmethod
    def _write_env_file(path: Path, env: dict[str, str], on_event: EventFn) -> None:
        lines = []
        for key, value in env.items():
            if not ENV_KEY.match(key) or key.startswith("FR_"):
                on_event("warn", f"Ignoring environment variable with an unusable name: {key}", None)
                continue
            if "\n" in value or "\r" in value:
                on_event("warn", f"Ignoring {key}: multi-line values are not supported", None)
                continue
            lines.append(f"{key}={value}")
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines) + ("\n" if lines else ""))
        os.chmod(path, 0o600)

    def _create_args(self, name: str, env_file: Path) -> list[str]:
        return [
            "create", "--name", name, "--label", "firstrun=1", "--init",
            "--memory", self.memory, "--cpus", self.cpus, "--pids-limit", str(self.pids_limit),
            "--security-opt", "no-new-privileges",
            "-e", "FR_WORKDIR=/work", "-e", "FR_STATE=/firstrun",
            "-e", "PYTHONUNBUFFERED=1", "-e", "PIP_DISABLE_PIP_VERSION_CHECK=1", "-e", "PIP_DEFAULT_TIMEOUT=60",
            "-e", "PIP_ROOT_USER_ACTION=ignore",
            "--env-file", str(env_file),
            "-v", f"{self.pip_cache_volume}:/root/.cache/pip",
            "-w", "/work", self._run_image or self.image, "bash", "/firstrun/run.sh",
        ]

    def run(self, project_dir: Path, steps: list[Step], *, env: Optional[dict[str, str]] = None,
            label: str = "as documented", on_event: EventFn = noop_event,
            timeout: int = 900) -> RunResult:
        started = time.monotonic()
        ok, reason = self.available()
        if not ok:
            return self._error(label, steps, started, reason)
        problem = self._ensure_image(on_event)
        if problem:
            return self._error(label, steps, started, problem)

        token = secrets.token_hex(6)
        name = f"firstrun-{token}"
        tmp = Path(tempfile.mkdtemp(prefix="firstrun-"))
        env_file = tmp / "env.list"
        created = False
        try:
            work = copy_project(Path(project_dir), tmp / "work")
            state = tmp / "state"
            self._write_state(state, steps, token, self.watch_seconds)
            self._write_env_file(env_file, env or {}, on_event)
            p = self._docker(*self._create_args(name, env_file), timeout=120)
            # docker has read the values by now, no reason to keep them on disk
            env_file.unlink(missing_ok=True)
            if p.returncode != 0:
                return self._error(label, steps, started, f"docker create failed: {self._last_line(p)}")
            created = True
            for src, dest in ((work, "/work"), (state, "/firstrun")):
                p = self._docker("cp", f"{src}/.", f"{name}:{dest}", timeout=300)
                if p.returncode != 0:
                    return self._error(label, steps, started, f"docker cp failed: {self._last_line(p)}")

            collector = _Collector(steps, token, on_event)
            rc, timed_out, _ = _stream(
                ["docker", "start", "-a", name], on_line=collector.handle,
                deadline=time.monotonic() + timeout,
                kill=lambda _p: self._docker("kill", name, timeout=30),
            )
            return self._build(label, steps, token, collector, rc, timed_out, started)
        finally:
            env_file.unlink(missing_ok=True)
            if created:
                try:
                    self._docker("rm", "-f", name, timeout=60)
                except (OSError, subprocess.SubprocessError):
                    pass
            shutil.rmtree(tmp, ignore_errors=True)


def _uses(pattern: re.Pattern, steps: list[Step]) -> bool:
    return any(pattern.search(s.command) for s in steps if not s.provided_by_firstrun)


def has_python_manifest(project_dir: Path) -> bool:
    return any((project_dir / n).is_file() for n in PYTHON_MANIFESTS) or any(project_dir.glob("requirements*.txt"))


def pick_image(project_dir: Path, steps: list[Step], requested: str) -> tuple[str, bool, Optional[str]]:
    """Choose the container image for a project when the user did not pick one.

    Returns (image, install_node, reason). install_node means: keep the Python image and add a
    FirstRun provided step that installs Node first. Without package.json a stray `npm start`
    is a README problem, so it is left to fail.
    """
    if requested != DEFAULT_IMAGE:
        return requested, False, None
    if not (project_dir / "package.json").is_file() or not _uses(NODE_CMD_RE, steps):
        return requested, False, None
    if has_python_manifest(project_dir) or _uses(PYTHON_CMD_RE, steps):
        return requested, True, ("the project has package.json and its README runs Node commands as well "
                                 "as Python ones, so FirstRun installs Node in the Python image first")
    return NODE_IMAGE, False, (f"the project has package.json, no Python manifest and its README runs Node "
                               f"commands, so FirstRun uses {NODE_IMAGE}")


def node_prerequisite(steps: list[Step]) -> list[Step]:
    """Prepend the Node install step (idempotent) and renumber."""
    if any(s.provided_by_firstrun and s.command == NODE_INSTALL for s in steps):
        return steps
    first = Step(index=1, command=NODE_INSTALL, kind="prerequisite", section="Prerequisites",
                 purpose="Node.js for a project with package.json (installed by FirstRun)",
                 provided_by_firstrun=True)
    out = [first] + list(steps)
    for i, s in enumerate(out, 1):
        s.index = i
    return out


def make_sandbox(kind: str, *, image: str = DEFAULT_IMAGE, watch_seconds: int = 20) -> Sandbox:
    if kind == "docker":
        return DockerSandbox(image=image, watch_seconds=watch_seconds)
    if kind == "local":
        return LocalSandbox(watch_seconds=watch_seconds)
    raise ValueError(f"unknown sandbox: {kind} (use docker or local)")
