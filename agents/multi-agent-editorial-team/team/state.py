"""Enterprise Pydantic data contracts and TeamState for Multi-Agent Pipeline."""

import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field


class AgentRole(str, Enum):
    """The specialized persona roles in the collaborative team."""
    PLANNER = "planner"
    RESEARCHER = "researcher"
    WRITER = "writer"
    REVIEWER = "reviewer"
    ORCHESTRATOR = "orchestrator"


class ReviewStatus(str, Enum):
    """Review gate verdict status."""
    APPROVED = "APPROVED"
    REVISE = "REVISE"


class CritiqueItem(BaseModel):
    """Individual critique observation from the Reviewer Agent."""
    aspect: str = Field(..., description="Target dimension: Accuracy, Citations, Clarity, Structure")
    feedback: str = Field(..., description="Constructive criticism and issue identified")
    severity: str = Field(default="medium", description="Severity: low, medium, critical")


class ReviewVerdict(BaseModel):
    """Structured evaluation verdict from the Reviewer Agent."""
    score: int = Field(..., ge=0, le=100, description="Overall quality score from 0 to 100")
    status: ReviewStatus = Field(..., description="APPROVED or REVISE")
    summary: str = Field(..., description="Executive verdict rationale")
    critiques: List[CritiqueItem] = Field(default_factory=list, description="Specific feedback items")
    revision_suggestions: List[str] = Field(default_factory=list, description="Actionable revision steps")


class EvidenceItem(BaseModel):
    """Verified search finding collected by the Researcher Agent."""
    title: str
    url: str
    snippet: str
    verified: bool = True


class ArticlePlan(BaseModel):
    """Topic decomposition and outline generated by the Planner Agent."""
    title: str
    target_audience: str
    key_sections: List[str] = Field(default_factory=list)
    search_queries: List[str] = Field(default_factory=list)


class AgentMessage(BaseModel):
    """Standardized inter-agent communication envelope."""
    message_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    sender: AgentRole
    recipient: AgentRole
    turn: int
    content: str
    timestamp: datetime.datetime = Field(default_factory=datetime.datetime.now)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class EditorialMetrics(BaseModel):
    """Operational audit and performance metrics for the team pipeline."""
    run_id: str
    topic: str
    started_at: datetime.datetime
    completed_at: Optional[datetime.datetime] = None
    duration_seconds: float = 0.0
    revision_count: int = 0
    final_score: int = 0
    total_evidence_gathered: int = 0
    agent_messages_exchanged: int = 0
    status: str = "in_progress"
    mock_mode: bool = False


class TeamState(BaseModel):
    """Centralized, state-machine snapshot representing the collaborative workspace."""
    topic: str
    plan: Optional[ArticlePlan] = None
    evidence: List[EvidenceItem] = Field(default_factory=list)
    draft_history: List[str] = Field(default_factory=list)
    current_draft: str = ""
    verdict_history: List[ReviewVerdict] = Field(default_factory=list)
    latest_verdict: Optional[ReviewVerdict] = None
    messages: List[AgentMessage] = Field(default_factory=list)
    revision_turns: int = 0
    max_revisions: int = 2
    pass_score: int = 85
    is_approved: bool = False
    metrics: Optional[EditorialMetrics] = None

    def record_message(self, sender: AgentRole, recipient: AgentRole, content: str, turn: int, metadata: Optional[Dict[str, Any]] = None):
        """Appends a typed inter-agent message to the audit log."""
        msg = AgentMessage(
            sender=sender,
            recipient=recipient,
            turn=turn,
            content=content,
            metadata=metadata or {}
        )
        self.messages.append(msg)
        return msg
