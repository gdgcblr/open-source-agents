"""Measure dead-code-reaper against the hand-labelled example project.

Usage:  python eval/run_eval.py          (writes eval/results.md)

It compares three stages against eval/ground_truth.json:
  1. static scan only     - everything the analyzer flags
  2. after verification   - flagged, and the tests still pass without it
  3. ticked by default    - what `apply` removes if you accept the report as is
For stage 1 and 3 it also deletes the code and runs the example's tests, to
show what a naive "delete everything flagged" approach would do.
"""
from __future__ import annotations

import json
import platform
import shutil
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from dead_code_reaper.analyzer import scan  # noqa: E402
from dead_code_reaper.verifier import check_selection, verify  # noqa: E402

EXAMPLE = HERE.parent / "examples" / "inventory_app"


def score(name: str, keys: set[str], truth: dict, tests_pass: bool | None) -> dict:
    dead, alive = set(truth["dead"]), set(truth["alive"])
    found = keys & dead
    wrong = keys & alive
    unknown = keys - dead - alive
    return {
        "stage": name, "flagged": len(keys), "dead_found": len(found), "dead_total": len(dead),
        "recall": len(found) / len(dead), "precision": len(found) / len(keys) if keys else 1.0,
        "wrong": sorted(wrong), "unlabelled": sorted(unknown), "tests_pass": tests_pass,
    }


def main() -> int:
    truth = json.loads((HERE / "ground_truth.json").read_text())
    tmp = Path(tempfile.mkdtemp()) / "inventory_app"
    shutil.copytree(EXAMPLE, tmp, ignore=shutil.ignore_patterns("__pycache__", "reaper-out"))
    try:
        started = time.time()
        result = scan(tmp, mode="app")
        scan_s = time.time() - started
        flagged = {r.key for r in result.removals}

        ok_naive, _, _ = check_selection(str(tmp), result.sources, result.removals, "tests", None, 600)

        verified = verify(result, log=lambda m: None)
        proven = {r.key for r in result.removals if r.status == "verified"}
        ticked = [r for r in result.removals if r.status == "verified" and not r.default_keep]
        ok_ticked, _, _ = check_selection(str(tmp), result.sources, ticked, "tests", None, 600)

        rows = [
            score("1. Static scan only", flagged, truth, ok_naive),
            score("2. Verified against tests", proven, truth, None),
            score("3. Ticked by default", {r.key for r in ticked}, truth, ok_ticked),
        ]
        test_only = sorted(t.key for t in result.test_only)
    finally:
        shutil.rmtree(tmp.parent, ignore_errors=True)

    lines = [
        "# Evaluation results",
        "",
        "Generated by `python eval/run_eval.py` against `examples/inventory_app`. `eval/ground_truth.json`",
        "lists by hand what is really dead there (14 items) and 10 traps that",
        "look unused but aren't.",
        "",
        f"Python {platform.python_version()} on {platform.system()}. "
        f"Scan: {scan_s:.2f}s. Verification: {verified.runs} test runs, {verified.seconds:.1f}s.",
        "",
        "| Stage | Flagged | Dead code found | Precision | Wrongly flagged | Tests pass after deleting |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        tp = {True: "yes", False: "**no**", None: "n/a"}[r["tests_pass"]]
        lines.append(f"| {r['stage']} | {r['flagged']} | {r['dead_found']}/{r['dead_total']} "
                     f"({r['recall']:.0%}) | {r['precision']:.0%} | {len(r['wrong'])} | {tp} |")
    lines += ["", "Wrongly flagged at each stage:", ""]
    for r in rows:
        lines.append(f"- {r['stage']}: " + (", ".join(f"`{k}`" for k in r["wrong"]) or "none"))
        if r["unlabelled"]:
            lines.append(f"  - not in the ground truth: {', '.join(r['unlabelled'])}")
    expected_to = sorted(truth["test_only"])
    lines += ["", f"Test-only code reported: {', '.join(f'`{k}`' for k in test_only) or 'none'} "
              f"({'matches' if test_only == expected_to else 'does not match'} the ground truth).", ""]
    text = "\n".join(lines)
    (HERE / "results.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
