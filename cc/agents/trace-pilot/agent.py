import os
import json
from typing import Dict, Any, Optional
from tools import LogAnalyzerTool, TestInspectorTool

class TracePilotAgent:
    """TracePilot AI Agent: Investigates test failures and crash logs using evidence-linked diagnosis and generates a reproducible bug report."""

    def __init__(self, api_key: Optional[str] = None, model_name: str = "gemini-2.5-flash"):
        self.api_key = api_key or os.getenv("GEMINI_API_KEY")
        self.model_name = model_name

    def investigate(self, log_content: str, env_details: Optional[Dict[str, str]] = None) -> Dict[str, Any]:
        env_details = env_details or {
            "OS": "macOS / Linux",
            "Python Version": "3.11.5",
            "Test Framework": "pytest"
        }

        # Step 1: Run deterministic tool analysis (Evidence Gathering)
        log_analysis = LogAnalyzerTool.run(log_content)
        test_analysis = TestInspectorTool.run(log_content)

        # Step 2: Build Evidence-Linked Diagnosis
        confirmed_facts = []
        hypotheses = []

        if test_analysis["total_failures"] > 0:
            for test in test_analysis["failing_tests"]:
                confirmed_facts.append(f"Test '{test['test_name']}' failed at output line {test['line_number']}.")

        for err in log_analysis["errors_detected"]:
            confirmed_facts.append(f"Error encountered at line {err['line_number']}: {err['content']}")

        for frame in log_analysis["stack_frames"]:
            confirmed_facts.append(f"Stack frame in {frame['file']} at line {frame['line']} ({frame['function']}).")

        # Formulate hypotheses based on evidence
        if any("ConnectionPoolExhaustedError" in err["content"] for err in log_analysis["errors_detected"]):
            hypotheses.append({
                "hypothesis": "Database connection pool capacity is exceeded because active connections are not being properly released or timeout threshold is too short under load.",
                "confidence": "High",
                "supporting_evidence": "ConnectionPoolExhaustedError triggered when active=5, max=5."
            })
        else:
            hypotheses.append({
                "hypothesis": "Unhandled exception or assertion failure caused test execution termination.",
                "confidence": "Medium",
                "supporting_evidence": "Errors detected in log analysis."
            })

        # Step 3: Generate Reproduction Steps & Bug Report
        reproduction_steps = [
            "1. Check out the repository at the affected commit.",
            "2. Ensure test dependencies are installed (e.g. pytest).",
            "3. Execute test suite targeting the failing test module.",
            "4. Observe connection pool exhaustion or assertion failure."
        ]

        bug_report = {
            "title": f"Bug Report: {test_analysis['failing_tests'][0]['test_name'] if test_analysis['failing_tests'] else 'Application Error'}",
            "environment": env_details,
            "confirmed_facts": confirmed_facts,
            "hypotheses": hypotheses,
            "reproduction_steps": reproduction_steps,
            "expected_behavior": "Test suite passes successfully with all database connections managed cleanly.",
            "actual_behavior": f"Test failed with {test_analysis['total_failures']} failure(s) and error traceback.",
            "evidence_lines": log_analysis["evidence_line_numbers"]
        }

        return {
            "log_analysis": log_analysis,
            "test_analysis": test_analysis,
            "bug_report": bug_report
        }

    def render_markdown_report(self, report_data: Dict[str, Any]) -> str:
        br = report_data["bug_report"]
        ta = report_data["test_analysis"]
        la = report_data["log_analysis"]

        md = []
        md.append(f"# 🛡️ TracePilot Investigation Report")
        md.append(f"> **Generated by TracePilot AI Agent**\n")

        md.append(f"## 📋 Executive Summary")
        md.append(f"- **Total Tests Failed**: {ta['total_failures']}")
        md.append(f"- **Total Errors Logged**: {len(la['errors_detected'])}")
        md.append(f"- **Stack Frames Captured**: {len(la['stack_frames'])}")
        md.append(f"- **Evidence Line Numbers**: `{', '.join(map(str, la['evidence_line_numbers']))}`\n")

        md.append(f"## 🔍 Confirmed Facts (Evidence-Linked)")
        for fact in br["confirmed_facts"]:
            md.append(f"- ✅ {fact}")
        md.append("")

        md.append(f"## 🧠 Hypotheses & Root Cause Analysis")
        for hyp in br["hypotheses"]:
            md.append(f"- **Hypothesis**: {hyp['hypothesis']}")
            md.append(f"  - **Confidence**: `{hyp['confidence']}`")
            md.append(f"  - **Supporting Evidence**: {hyp['supporting_evidence']}")
        md.append("")

        md.append(f"## 👣 Reproduction Steps")
        for step in br["reproduction_steps"]:
            md.append(step)
        md.append("")

        md.append(f"## ⚖️ Expected vs. Actual Behavior")
        md.append(f"- **Expected Behavior**: {br['expected_behavior']}")
        md.append(f"- **Actual Behavior**: {br['actual_behavior']}\n")

        md.append(f"## ⚙️ Environment Details")
        for k, v in br["environment"].items():
            md.append(f"- **{k}**: {v}")

        return "\n".join(md)
